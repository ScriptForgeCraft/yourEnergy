import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { extname, relative, resolve, sep } from 'node:path';

const CACHE_PREFIX = 'yourenergy-';
const RUNTIME_CACHE = `${CACHE_PREFIX}runtime-v1`;
const SERVICE_WORKER_FILE = 'sw.js';
const HOME_DOCUMENTS = new Set(['index.html', 'ru/index.html', 'en/index.html']);

export const toPrecacheUrl = (file) => {
  const normalized = file.split(sep).join('/');
  if (normalized === 'index.html') return '/';
  if (normalized.endsWith('/index.html')) return `/${normalized.slice(0, -'index.html'.length)}`;
  return `/${normalized}`;
};

const walk = async (directory) => {
  const entries = await readdir(directory, { withFileTypes: true });
  return (
    await Promise.all(
      entries.map((entry) => {
        const file = resolve(directory, entry.name);
        return entry.isDirectory() ? walk(file) : [file];
      })
    )
  ).flat();
};

/**
 * Keep installation deliberately light: the three localized home documents
 * and exactly the assets their first render needs. Other routes are warmed
 * only after the home page has settled on a suitable connection.
 */
export const isPrecachePath = (file) => {
  const extension = extname(file).toLowerCase();
  if (HOME_DOCUMENTS.has(file)) return true;
  if (file.startsWith('assets/')) {
    return /(?:^|\/)(?:home-[^/]+\.css|main-[^/]+\.js|navigation-[^/]+\.js|home-motion-[^/]+\.js|calculator-session-[^/]+\.js)$/u.test(
      file
    );
  }
  if (file.startsWith('fonts/')) return extension === '.woff2';
  if (file === 'scripts/process-reload-restoration.js') return true;
  return ['favicon.ico', 'icons.svg', 'yourenergy-mark.svg', 'offline.html'].includes(file);
};

export const renderServiceWorker = ({
  revision,
  precacheUrls,
  staticDocumentUrls = []
}) => `/* Generated at build time. Do not edit this file directly. */
'use strict';

const CACHE_PREFIX = ${JSON.stringify(CACHE_PREFIX)};
const PRECACHE = \`${CACHE_PREFIX}precache-${revision}\`;
const RUNTIME_CACHE = ${JSON.stringify(RUNTIME_CACHE)};
const OFFLINE_URL = '/offline.html';
const NAVIGATION_TIMEOUT_MS = 3500;
const MAX_RUNTIME_ENTRIES = 80;
const MAX_WARM_URLS = 12;
const PRECACHE_URLS = ${JSON.stringify(precacheUrls)};
const STATIC_DOCUMENT_PATHS = new Set(${JSON.stringify(staticDocumentUrls)});

const isCacheable = (response) =>
  Boolean(response && response.ok && response.type === 'basic') &&
  !/no-store/iu.test(response.headers.get('cache-control') || '');

const isApiRequest = (url) => url.pathname.startsWith('/api/');
const isRuntimeData = (url) => url.pathname === '/data/meeting-schedule.json';
const isKnownStaticDocument = (url) => STATIC_DOCUMENT_PATHS.has(url.pathname);
const isStaticAsset = (request, url) =>
  ['style', 'script', 'font', 'image'].includes(request.destination) ||
  /^(?:\\/assets\\/|\\/fonts\\/|\\/images\\/|\\/documents\\/|\\/maps\\/|\\/scripts\\/)/u.test(url.pathname);
const isWarmableUrl = (url) =>
  url.origin === self.location.origin &&
  !isApiRequest(url) &&
  (isKnownStaticDocument(url) || isStaticAsset({ destination: '' }, url));

const trimRuntimeCache = async (cache) => {
  const keys = await cache.keys();
  await Promise.all(keys.slice(0, Math.max(0, keys.length - MAX_RUNTIME_ENTRIES)).map((key) => cache.delete(key)));
};

const putRuntime = async (request, response) => {
  if (!isCacheable(response)) return;
  const cache = await caches.open(RUNTIME_CACHE);
  await cache.delete(request, { ignoreSearch: false });
  await cache.put(request, response.clone());
  await trimRuntimeCache(cache);
};

const matchCached = async (request) => {
  const precache = await caches.open(PRECACHE);
  const precached = await precache.match(request, { ignoreSearch: true });
  return precached || caches.match(request, { ignoreSearch: true });
};

const offlineFallback = async (request) => {
  const cached = await matchCached(request);
  if (cached) return cached;
  const precache = await caches.open(PRECACHE);
  return (await precache.match(OFFLINE_URL)) || Response.error();
};

const navigationResponse = async (request) => {
  const url = new URL(request.url);
  const canCacheDocument = isKnownStaticDocument(url);
  const cached = canCacheDocument ? await matchCached(request) : null;
  let timeoutId;
  const network = fetch(request)
    .then(async (response) => {
      if (
        canCacheDocument &&
        isCacheable(response) &&
        /text\\/html/iu.test(response.headers.get('content-type') || '')
      ) {
        await putRuntime(request, response);
      }
      return response;
    })
    .catch(() => null);
  const timeout = new Promise((resolve) => {
    timeoutId = setTimeout(() => resolve(null), NAVIGATION_TIMEOUT_MS);
  });
  if (cached) {
    void network;
    clearTimeout(timeoutId);
    return cached;
  }
  const response = await Promise.race([network, timeout]);
  clearTimeout(timeoutId);
  if (response) return response;
  if (canCacheDocument) return offlineFallback(request);
  const precache = await caches.open(PRECACHE);
  return (await precache.match(OFFLINE_URL)) || Response.error();
};

const staleWhileRevalidate = async (request) => {
  const cached = await matchCached(request);
  const network = fetch(request)
    .then(async (response) => {
      await putRuntime(request, response);
      return response;
    })
    .catch(() => null);
  return cached || (await network) || Response.error();
};

const cacheFirst = async (request) => {
  const cached = await matchCached(request);
  if (cached) return cached;
  try {
    const response = await fetch(request);
    await putRuntime(request, response);
    return response;
  } catch {
    return Response.error();
  }
};

const extractWarmDependencies = (markup) => {
  const urls = new Set();
  for (const match of markup.matchAll(/\\b(?:src|href)\\s*=\\s*(['"])([^'"]+)\\1/giu)) {
    try {
      const url = new URL(match[2], self.location.origin);
      if (isWarmableUrl(url) && isStaticAsset({ destination: '' }, url)) urls.add(url.href);
    } catch {
      // Ignore malformed or third-party document URLs during opportunistic warming.
    }
  }
  return [...urls];
};

const warmUrl = async (value, { includeDependencies = true } = {}) => {
  let url;
  try {
    url = new URL(value, self.location.origin);
  } catch {
    return;
  }
  if (!isWarmableUrl(url)) return;

  const request = new Request(url.href, { credentials: 'same-origin' });
  if (await matchCached(request)) return;
  try {
    const response = await fetch(request);
    if (!isCacheable(response)) return;
    await putRuntime(request, response);
    if (!includeDependencies || !/text\\/html/iu.test(response.headers.get('content-type') || '')) return;
    const dependencies = extractWarmDependencies(await response.clone().text());
    for (const dependency of dependencies) await warmUrl(dependency, { includeDependencies: false });
  } catch {
    // Warming is intentionally best-effort and must never affect navigation.
  }
};

const warmUrls = async (urls) => {
  if (!Array.isArray(urls)) return;
  for (const url of [...new Set(urls)].slice(0, MAX_WARM_URLS)) await warmUrl(url);
};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(PRECACHE).then(async (cache) => {
      await Promise.all(
        PRECACHE_URLS.map(async (url) => {
          const response = await fetch(url, { cache: 'no-cache' });
          if (!response.ok) throw new Error(\`Precache failed for \${url}: \${response.status}\`);
          await cache.put(url, response);
        })
      );
    })
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith(CACHE_PREFIX) && key !== PRECACHE && key !== RUNTIME_CACHE)
            .map((key) => caches.delete(key))
        )
      )
      .then(() => self.clients.claim())
  );
});

self.addEventListener('message', (event) => {
  if (event.data?.type === 'YOUR_ENERGY_SKIP_WAITING') self.skipWaiting();
  if (event.data?.type === 'YOUR_ENERGY_WARM_URLS') event.waitUntil(warmUrls(event.data.urls));
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET' || request.headers.has('range')) return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin || isApiRequest(url)) return;

  if (request.mode === 'navigate') {
    event.respondWith(navigationResponse(request));
    return;
  }

  if (isRuntimeData(url) || request.destination === 'image') {
    event.respondWith(staleWhileRevalidate(request));
    return;
  }

  if (isStaticAsset(request, url)) event.respondWith(cacheFirst(request));
});
`;

export const writeServiceWorker = async ({ distRoot }) => {
  const outputFiles = (await walk(distRoot))
    .map((file) => relative(distRoot, file).split(sep).join('/'))
    .filter((file) => file !== SERVICE_WORKER_FILE)
    .sort();
  const staticDocumentUrls = outputFiles
    .filter((file) => file.endsWith('.html'))
    .map(toPrecacheUrl);
  const files = outputFiles.filter(isPrecachePath);
  const revisionHash = createHash('sha256');
  for (const file of files) {
    revisionHash.update(file);
    revisionHash.update(toPrecacheUrl(file));
    revisionHash.update(await readFile(resolve(distRoot, file)));
  }
  const revision = revisionHash.digest('hex').slice(0, 16);
  await writeFile(
    resolve(distRoot, SERVICE_WORKER_FILE),
    renderServiceWorker({
      revision,
      precacheUrls: files.map(toPrecacheUrl),
      staticDocumentUrls
    }),
    'utf8'
  );
};
